export function validateSamsungArchiveEntry(id,entry){
  if(!/^samsung-galaxy-[a-z0-9-]+$/.test(id)||!entry?._modelName)return false;
  if(entry.dataQuality!=='official-specifications-samsung-newsroom')return false;
  let url;
  try{url=new URL(entry.sourceUrl)}catch{return false}
  if(url.protocol!=='https:'||url.hostname!=='news.samsung.com')return false;
  if(!String(entry.verifiedSource||'').startsWith('Samsung Newsroom'))return false;
  return Object.keys(entry).filter(key=>![
    'sourceUrl','verifiedAt','verifiedSource','sourceKind','dataQuality','variantDetails','_modelName'
  ].includes(key)).length>=4;
}
