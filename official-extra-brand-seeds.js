export const EXTRA_BRAND_FILES=Object.freeze({Xiaomi:'official-xiaomi.json',Infinix:'official-infinix.json',Tecno:'official-tecno.json',Itel:'official-itel.json'});

export function exactBrandModelName(brand,name){
  const raw=String(name||'').toLowerCase().normalize('NFKD').trim();
  const prefix=String(brand||'').toLowerCase();
  const trimmed=raw.startsWith(prefix+' ')?raw.slice(prefix.length+1):raw;
  // Keep REDMI, POCO, 4G/5G, Plus/Pro/Ultra tokens; variants cannot merge.
  return trimmed.replace(/\+/g,'plus').replace(/[^a-z0-9]+/g,'');
}
export function manufacturerSeedRecord(seed){
  return {
    ...seed.specs,
    sourceUrl:seed.url,
    verifiedSource:seed.brand+' official product specification page',
    dataQuality:'official-specifications-launch-reference',
    variantDetails:'Reference information from '+seed.brand+' launch/product page. Hardware, storage, memory, networks and specifications can differ by region and revision.'
  };
}
export function materializeManufacturerSeeds(catalog){
  const out=Object.fromEntries(Object.keys(EXTRA_BRAND_FILES).map(b=>[b,{}]));
  for(const seed of EXTRA_BRAND_SEEDS){
    const matches=(catalog||[]).filter(p=>
      (p.brand?.toLowerCase()===seed.brand.toLowerCase()||(seed.brand==='Xiaomi'&&['poco','redmi'].includes(p.brand?.toLowerCase())))&&
      exactBrandModelName(seed.brand,p.name)===exactBrandModelName(seed.brand,seed.name));
    // Exact one-model identity only: if catalog has ambiguous duplicate names,
    // do not guess which ID represents this launch reference.
    if(matches.length!==1)continue;
    out[seed.brand][matches[0].id]=manufacturerSeedRecord(seed);
  }
  return out;
}
